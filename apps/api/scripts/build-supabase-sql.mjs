// Builds the two SQL files to paste into the Supabase SQL editor (see docs/SUPABASE_SQL.md):
//   supabase/01-schema.sql          final schema for an EMPTY database (refuses to run if tables exist), RLS on, Prisma history baselined
//   supabase/02-catalogue-seed.sql  categories + products + one blank option each (hidden, unpriced), idempotent
// Usage: node scripts/build-supabase-sql.mjs   (run from apps/api; needs `pnpm install`)
import { execFileSync } from 'node:child_process';
import { createHash, randomUUID } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('../../../', import.meta.url).pathname;
const out = join(root, 'supabase');
mkdirSync(out, { recursive: true });

const ddl = execFileSync('node', ['scripts/dev-ddl.mjs'], { encoding: 'utf8' });
const constraints = readFileSync('prisma/sql/constraints.sql', 'utf8');
const m6 = readFileSync('prisma/migrations/0006_cod_only_rls/migration.sql', 'utf8');
const rls = m6.slice(m6.indexOf('DO $$\nDECLARE t record;'));
const migrations = readdirSync('prisma/migrations', { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort();
const history = migrations.map((n) => {
  const sum = createHash('sha256').update(readFileSync(`prisma/migrations/${n}/migration.sql`)).digest('hex');
  return `  ('${randomUUID()}', '${sum}', now(), '${n}', NULL, NULL, now(), 1)`;
});

const schema = `-- Dudhwala: final database schema for an EMPTY Supabase database.
-- Paste into Supabase -> SQL Editor -> Run. Generated by apps/api/scripts/build-supabase-sql.mjs; do not edit by hand.
-- Equivalent to prisma migrations ${migrations.join(', ')} applied in order.
-- Safe by design: it stops with an error if the public schema already contains any table, so it can never wipe data.

DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_tables WHERE schemaname = 'public') THEN
    RAISE EXCEPTION 'public schema is not empty: this script is for a brand-new database only. Nothing was changed.';
  END IF;
END $$;

${ddl}
${constraints}

-- Row Level Security: every table locked against Supabase's public Data API (no policies; only the API's server-side connection reads/writes).
${rls}

-- Tell Prisma these migrations are already applied, so a later \`prisma migrate deploy\` does nothing and only applies future migrations.
CREATE TABLE "_prisma_migrations" (
  id VARCHAR(36) PRIMARY KEY NOT NULL,
  checksum VARCHAR(64) NOT NULL,
  finished_at TIMESTAMPTZ,
  migration_name VARCHAR(255) NOT NULL,
  logs TEXT,
  rolled_back_at TIMESTAMPTZ,
  started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  applied_steps_count INTEGER NOT NULL DEFAULT 0
);
ALTER TABLE "_prisma_migrations" ENABLE ROW LEVEL SECURITY;
INSERT INTO "_prisma_migrations" (id, checksum, finished_at, migration_name, logs, rolled_back_at, started_at, applied_steps_count) VALUES
${history.join(',\n')};
`;
writeFileSync(join(out, '01-schema.sql'), schema);

const cat = JSON.parse(readFileSync(join(root, 'demo/mock-api/catalogue.json'), 'utf8'));
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const outer = (v) => (v ? q(v.toUpperCase()) : 'NULL');
let seed = `-- Dudhwala: product catalogue (names and Outer Sylhet marks only; NO prices, sizes, stock or photos exist in the source).
-- Run AFTER 01-schema.sql. Idempotent: re-running adds nothing and never overwrites admin edits.
-- Products arrive HIDDEN (active=false) and unpriced; set price/stock/photo in the admin, then switch them on.
BEGIN;
`;
cat.categories.forEach((c, i) => {
  seed += `INSERT INTO category (id, slug, name_bn, name_en, sort_order, active) VALUES (gen_random_uuid(), ${q(c.slug)}, ${q(c.nameBn)}, ${q(c.nameEn)}, ${i}, true) ON CONFLICT (slug) DO NOTHING;\n`;
});
seed += '\nWITH new_products AS (\n  INSERT INTO product (id, category_id, slug, name_bn, name_en, name_verified, outer_city_status, active, updated_at)\n  SELECT gen_random_uuid(), c.id, v.slug, v.name_bn, v.name_en, v.verified, v.outer_status::"OuterCityStatus", false, now()\n  FROM (VALUES\n';
seed += cat.products.map((p) => `    (${q(p.id)}, ${q(p.category)}, ${q(p.nameBn)}, ${q(p.nameEn)}, ${p.nameVerified ? 'true' : 'false'}, ${p.outerCity ? q(p.outerCity.toUpperCase()) : 'NULL'})`).join(',\n');
seed += `\n  ) AS v(slug, cat, name_bn, name_en, verified, outer_status)\n  JOIN category c ON c.slug = v.cat\n  ON CONFLICT (slug) DO NOTHING\n  RETURNING id\n)\nINSERT INTO product_variant (id, product_id, updated_at) SELECT gen_random_uuid(), id, now() FROM new_products;\nCOMMIT;\n`;
writeFileSync(join(out, '02-catalogue-seed.sql'), seed);
console.log('written supabase/01-schema.sql and 02-catalogue-seed.sql');
