#!/usr/bin/env bash
# Builds and (re)starts the local stack for end-to-end tests:
#   API :4000 (demo seed loaded), storefront :3000, admin :3001.
# Requires apps/api/.env (see .env.example) with ENABLE_DEV_OUTBOX=true and a reachable DATABASE_URL.
# Usage: e2e/stack.sh [--fresh-db]   (fresh DB needs PSQL_ADMIN_URL pointing at the server's postgres db)
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
LOGS="${STACK_LOGS:-$ROOT/e2e/.stack}"
mkdir -p "$LOGS"

# Stop whatever listens on the stack's ports (process titles vary, e.g. "next-server").
stop() {
  for port in 4000 3000 3001; do
    fuser -k -TERM "$port/tcp" >/dev/null 2>&1 || true
  done
  sleep 1
}
stop
[[ "${1:-}" == "--fresh-db" ]] && FRESH_DB=1

# API runs with its own .env in a subshell so its NODE_ENV never leaks into the Next.js builds.
(
  cd "$ROOT/apps/api"
  set -a; . ./.env; set +a
  if [[ "${FRESH_DB:-}" == "1" ]]; then
    DB="${DATABASE_URL##*/}"
    psql "$PSQL_ADMIN_URL" -qc "DROP DATABASE IF EXISTS $DB WITH (FORCE)" -c "CREATE DATABASE $DB"
    for m in prisma/migrations/*/migration.sql; do psql "$DATABASE_URL" -q -v ON_ERROR_STOP=1 -f "$m" >/dev/null; done
  fi
  pnpm -s build
  node dist/seed/demo/demo-seed.js seed
  nohup node dist/main.js > "$LOGS/api.log" 2>&1 &
  # Slots are generated by a background job after boot; wait for them so the storefront
  # build and first requests never cache "unavailable" from an empty slot table.
  for _ in $(seq 1 60); do
    n=$(psql "$DATABASE_URL" -tAc "SELECT count(*) FROM delivery_slot WHERE status = 'OPEN'" 2>/dev/null || echo 0)
    [[ "${n:-0}" -gt 0 ]] && break
    sleep 1
  done
)
unset NODE_ENV

cd "$ROOT/apps/web"
# Drop the Next.js data cache: it would otherwise serve catalogue pages (with old ids) from a previous database.
rm -rf .next/cache
NEXT_PUBLIC_API_URL="${NEXT_PUBLIC_API_URL:-http://localhost:4000/v1}" pnpm -s build > "$LOGS/web-build.log"
NEXT_PUBLIC_API_URL="${NEXT_PUBLIC_API_URL:-http://localhost:4000/v1}" API_INTERNAL_URL=http://localhost:4000/v1 nohup npx next start -p 3000 > "$LOGS/web.log" 2>&1 &

if [[ -d "$ROOT/apps/admin" ]]; then
  cd "$ROOT/apps/admin"
  NEXT_PUBLIC_API_URL="${NEXT_PUBLIC_API_URL:-http://localhost:4000/v1}" pnpm -s build > "$LOGS/admin-build.log"
  NEXT_PUBLIC_API_URL="${NEXT_PUBLIC_API_URL:-http://localhost:4000/v1}" nohup npx next start -p 3001 > "$LOGS/admin.log" 2>&1 &
fi

for url in http://localhost:4000/v1/health/ready http://localhost:3000/ http://localhost:3001/login; do
  for _ in $(seq 1 60); do curl -sf -o /dev/null "$url" && break; sleep 1; done
done
echo "stack ready (logs in $LOGS)"
